package main

import (
	"fmt"
	"go/format"
	"go/types"
	"sort"
	"strings"
)

type goEmitter struct {
	m       *model
	aliases map[string]string // caminho do pacote → alias no import
	used    map[string]bool
	helpers map[string]string // chave → nome da função auxiliar
	code    []string          // funções auxiliares, na ordem de criação
}

func emitGo(m *model, fns []*fn) ([]byte, error) {
	g := &goEmitter{m: m, aliases: map[string]string{}, used: map[string]bool{}, helpers: map[string]string{}}
	var reg, bodies []string
	for i, f := range fns {
		if f.why != "" {
			continue
		}
		name := fmt.Sprintf("fn%d", i)
		if f.stream != nil {
			reg = append(reg, fmt.Sprintf("reg[%q] = entry{stream: %s}", f.key, name))
		} else {
			reg = append(reg, fmt.Sprintf("reg[%q] = entry{call: %s}", f.key, name))
		}
		bodies = append(bodies, g.function(name, f))
	}
	var b strings.Builder
	b.WriteString("// Code generated by ipfs_ffi/go/gen from gen/roots.txt. DO NOT EDIT.\n\npackage main\n\nimport (\n")
	b.WriteString("\t\"encoding/json\"\n\t\"fmt\"\n\t\"io\"\n")
	for _, path := range sortedKeys(g.aliases) {
		fmt.Fprintf(&b, "\t%s %q\n", g.aliases[path], path)
	}
	b.WriteString(")\n\nvar (\n\t_ = fmt.Errorf\n\t_ = io.Discard\n)\n\n")
	b.WriteString("func init() {\n")
	for _, r := range reg {
		b.WriteString("\t" + r + "\n")
	}
	b.WriteString("}\n\n")
	b.WriteString("func nargs(a []json.RawMessage, n int) error {\n\tif len(a) != n {\n\t\treturn fmt.Errorf(\"ipfs_ffi: %d argumentos, esperava %d\", len(a), n)\n\t}\n\treturn nil\n}\n\n")
	for _, body := range bodies {
		b.WriteString(body + "\n")
	}
	for _, c := range g.code {
		b.WriteString(c + "\n")
	}
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return []byte(b.String()), fmt.Errorf("zz_generated.go não compila (gofmt): %w", err)
	}
	return src, nil
}

func (g *goEmitter) qual(p *types.Package) string {
	if a, ok := g.aliases[p.Path()]; ok {
		return a
	}
	base := "p_" + strings.NewReplacer("-", "_", ".", "_").Replace(p.Name())
	a := base
	for i := 2; g.used[a]; i++ {
		a = fmt.Sprintf("%s%d", base, i)
	}
	g.aliases[p.Path()], g.used[a] = a, true
	return a
}

func (g *goEmitter) ts(t types.Type) string { return types.TypeString(t, g.qual) }

// function emite a função registrada para f: decodifica os argumentos,
// chama e codifica o resultado (ou emite os itens do canal).
func (g *goEmitter) function(name string, f *fn) string {
	var b strings.Builder
	ret := "return nil, err"
	if f.stream != nil {
		fmt.Fprintf(&b, "// %s\nfunc %s(a []json.RawMessage, emit func(any)) error {\n", f.key, name)
		ret = "return err"
	} else {
		fmt.Fprintf(&b, "// %s\nfunc %s(a []json.RawMessage) (any, error) {\n", f.key, name)
	}
	n := 0
	var args []string
	recv := ""
	if f.recv != nil {
		recv = "recv"
		fmt.Fprintf(&b, "\trecv, err := %s(a[%d])\n\tif err != nil {\n\t\t%s\n\t}\n", g.dec(f.recv), n, ret)
		n++
	}
	chanIdx := chanParam(f)
	for i, p := range f.params {
		v := fmt.Sprintf("p%d", i)
		switch {
		case p.t.k == kWriter:
			args = append(args, "io.Discard")
			continue
		case i == chanIdx:
			args = append(args, "ch")
			continue
		}
		fmt.Fprintf(&b, "\t%s, err := %s(a[%d])\n\tif err != nil {\n\t\t%s\n\t}\n", v, g.dec(p.t), n, ret)
		n++
		if p.variadic {
			v += "..."
		}
		args = append(args, v)
	}
	// nargs no início: o índice a[n] acima já depende do tamanho certo.
	head := fmt.Sprintf("\tif err := nargs(a, %d); err != nil {\n\t\t%s\n\t}\n", n, ret)
	body := strings.Replace(b.String(), "{\n", "{\n"+head, 1)
	b.Reset()
	b.WriteString(body)

	call := g.callee(f, recv) + "(" + strings.Join(args, ", ") + ")"
	if f.isVar {
		call = g.callee(f, recv)
		if f.conv != nil {
			call = g.ts(f.conv) + "(" + call + ")"
		}
	}
	declared := n > 0
	assign := func(lhs []string) string {
		op := ":="
		if len(lhs) == 1 && lhs[0] == "err" && declared {
			op = "="
		}
		return strings.Join(lhs, ", ") + " " + op + " "
	}
	var rs []string
	for i := range f.results {
		rs = append(rs, fmt.Sprintf("r%d", i))
	}
	lhs := append([]string{}, rs...)
	if f.hasErr {
		lhs = append(lhs, "err")
	}

	switch {
	case chanIdx >= 0: // chan<- passado: a função roda numa goroutine e o kubo fecha o canal
		fmt.Fprintf(&b, "\tch := make(chan %s)\n\terrc := make(chan error, 1)\n", g.ts(f.params[chanIdx].t.t.(*types.Chan).Elem()))
		if f.hasErr {
			fmt.Fprintf(&b, "\tgo func() { errc <- %s }()\n", call)
		} else {
			fmt.Fprintf(&b, "\tgo func() { %s; errc <- nil }()\n", call)
		}
		item := g.enc(f.stream, "v")
		fmt.Fprintf(&b, `	for {
		select {
		case v, ok := <-ch:
			if !ok {
				return <-errc
			}
			emit(%[1]s)
		case err := <-errc:
			for { // a função voltou: só resta o que já estava no canal
				select {
				case v, ok := <-ch:
					if !ok {
						return err
					}
					emit(%[1]s)
				default:
					return err
				}
			}
		}
	}
}
`, item)
		return b.String()
	case f.stream != nil: // <-chan devolvido
		fmt.Fprintf(&b, "\t%s%s\n", assign(append([]string{"ch"}, lhs[1:]...)), call)
		if f.hasErr {
			fmt.Fprintf(&b, "\tif err != nil {\n\t\treturn err\n\t}\n")
		}
		fmt.Fprintf(&b, "\tfor v := range ch {\n\t\temit(%s)\n\t}\n\treturn nil\n}\n", g.enc(f.stream, "v"))
		return b.String()
	}

	if len(lhs) == 0 {
		fmt.Fprintf(&b, "\t%s\n", call)
	} else {
		fmt.Fprintf(&b, "\t%s%s\n", assign(lhs), call)
	}
	if f.hasErr {
		fmt.Fprintf(&b, "\tif err != nil {\n\t\treturn nil, err\n\t}\n")
	}
	switch len(rs) {
	case 0:
		b.WriteString("\treturn nil, nil\n}\n")
	case 1:
		fmt.Fprintf(&b, "\treturn %s, nil\n}\n", g.enc(f.results[0], "r0"))
	default:
		var es []string
		for i, r := range f.results {
			es = append(es, g.enc(r, rs[i]))
		}
		fmt.Fprintf(&b, "\treturn []any{%s}, nil\n}\n", strings.Join(es, ", "))
	}
	return b.String()
}

func (g *goEmitter) callee(f *fn, recv string) string {
	if recv != "" {
		return recv + "." + f.obj.Name()
	}
	return g.qual(f.obj.Pkg()) + "." + f.obj.Name()
}

// helper devolve o nome da auxiliar [key], criando-a com [mk] na primeira vez.
func (g *goEmitter) helper(key, prefix string, mk func(name string) string) string {
	if name, ok := g.helpers[key]; ok {
		return name
	}
	name := fmt.Sprintf("%s%d", prefix, len(g.helpers))
	g.helpers[key] = name
	g.code = append(g.code, mk(name))
	return name
}

// plain: o encoding/json já sabe (des)serializar como o Dart espera.
func plain(t *tinfo) bool {
	switch t.k {
	case kBasic:
		return true
	case kSlice, kMap:
		return plain(t.elem)
	}
	return false
}

// dec devolve uma expressão F tal que F(raw) devolve (T, error).
func (g *goEmitter) dec(t *tinfo) string {
	switch {
	case t.k == kHandle && t.reader:
		return "decReader"
	case t.k == kBytes:
		return "decBytes"
	case t.k == kError:
		return "decErr"
	case t.k == kHandle, t.k == kCtx:
		return "hdec[" + g.ts(t.t) + "]"
	case plain(t):
		return "jdec[" + g.ts(t.t) + "]"
	case t.k == kValue && !t.ptr:
		return t.val.dec
	case t.k == kSlice && t.elem.k == kOpts:
		return g.decOpts(t.elem)
	}
	return g.helper("dec:"+t.key, "dec", func(name string) string {
		T := g.ts(t.t)
		var b strings.Builder
		fmt.Fprintf(&b, "func %s(raw json.RawMessage) (%s, error) {\n", name, T)
		switch {
		case t.ptr: // *T de valor ou DTO
			inner := *t
			inner.ptr, inner.t = false, t.t.(*types.Pointer).Elem()
			inner.key = types.TypeString(inner.t, nil)
			fmt.Fprintf(&b, "\tif string(raw) == \"null\" {\n\t\treturn nil, nil\n\t}\n\tv, err := %s(raw)\n\treturn &v, err\n}\n", g.dec(&inner))
		case t.k == kDTO:
			fmt.Fprintf(&b, "\tvar v %s\n\tvar m map[string]json.RawMessage\n\tif err := json.Unmarshal(raw, &m); err != nil || m == nil {\n\t\treturn v, err\n\t}\n", T)
			for _, f := range t.fields {
				if f.skipped != "" {
					continue
				}
				fmt.Fprintf(&b, "\tif r, ok := m[%q]; ok {\n\t\tx, err := %s(r)\n\t\tif err != nil {\n\t\t\treturn v, err\n\t\t}\n\t\tv.%s = x\n\t}\n", f.name, g.dec(f.t), f.name)
			}
			b.WriteString("\treturn v, nil\n}\n")
		case t.k == kSlice:
			fmt.Fprintf(&b, "\tvar rs []json.RawMessage\n\tif err := json.Unmarshal(raw, &rs); err != nil {\n\t\treturn nil, err\n\t}\n\tout := make(%s, len(rs))\n\tfor i, r := range rs {\n\t\tx, err := %s(r)\n\t\tif err != nil {\n\t\t\treturn nil, err\n\t\t}\n\t\tout[i] = x\n\t}\n\treturn out, nil\n}\n", T, g.dec(t.elem))
		case t.k == kMap:
			fmt.Fprintf(&b, "\tvar rs map[string]json.RawMessage\n\tif err := json.Unmarshal(raw, &rs); err != nil {\n\t\treturn nil, err\n\t}\n\tout := make(%s, len(rs))\n\tfor k, r := range rs {\n\t\tx, err := %s(r)\n\t\tif err != nil {\n\t\t\treturn nil, err\n\t\t}\n\t\tout[k] = x\n\t}\n\treturn out, nil\n}\n", T, g.dec(t.elem))
		default:
			panic("gen: sem decodificador para " + t.key)
		}
		return b.String()
	})
}

// decOpts: lista de opções funcionais [{"P": "Unixfs.Pin", "A": [...]}].
func (g *goEmitter) decOpts(t *tinfo) string {
	return g.helper("opts:"+t.key, "opts", func(name string) string {
		T := g.ts(t.t)
		var b strings.Builder
		fmt.Fprintf(&b, "func %s(raw json.RawMessage) ([]%s, error) {\n", name, T)
		fmt.Fprintf(&b, "\tvar items []struct {\n\t\tP string\n\t\tA []json.RawMessage\n\t}\n\tif err := json.Unmarshal(raw, &items); err != nil {\n\t\treturn nil, err\n\t}\n")
		fmt.Fprintf(&b, "\tout := make([]%s, 0, len(items))\n\tfor _, it := range items {\n\t\tswitch it.P {\n", T)
		pkg := g.qual(t.named.Obj().Pkg())
		for _, c := range usableCtors(t) {
			p := strings.Join(c.path, ".")
			fmt.Fprintf(&b, "\t\tcase %q:\n\t\t\tif err := nargs(it.A, %d); err != nil {\n\t\t\t\treturn nil, fmt.Errorf(\"%%s: %%w\", it.P, err)\n\t\t\t}\n", p, len(c.params))
			var args []string
			for i, pt := range c.params {
				fmt.Fprintf(&b, "\t\t\ta%d, err := %s(it.A[%d])\n\t\t\tif err != nil {\n\t\t\t\treturn nil, err\n\t\t\t}\n", i, g.dec(pt), i)
				args = append(args, fmt.Sprintf("a%d", i))
			}
			call := fmt.Sprintf("%s.%s(%s)", pkg, p, strings.Join(args, ", "))
			if c.hasErr {
				fmt.Fprintf(&b, "\t\t\to, err := %s\n\t\t\tif err != nil {\n\t\t\t\treturn nil, err\n\t\t\t}\n\t\t\tout = append(out, o)\n", call)
			} else {
				fmt.Fprintf(&b, "\t\t\tout = append(out, %s)\n", call)
			}
		}
		b.WriteString("\t\tdefault:\n\t\t\treturn nil, fmt.Errorf(\"ipfs_ffi: opção desconhecida %q\", it.P)\n\t\t}\n\t}\n\treturn out, nil\n}\n")
		return b.String()
	})
}

// usableCtors: construtores da opção cujos parâmetros atravessam, por caminho.
func usableCtors(t *tinfo) []optCtor {
	var out []optCtor
	for _, c := range t.ctors {
		if ok, _ := okOptCtor(c); ok {
			out = append(out, c)
		}
	}
	sort.Slice(out, func(i, j int) bool { return strings.Join(out[i].path, ".") < strings.Join(out[j].path, ".") })
	return out
}

// enc devolve uma expressão (any) com o valor [expr] codificado.
func (g *goEmitter) enc(t *tinfo, expr string) string {
	switch {
	case t.k == kBasic:
		if b, ok := t.t.Underlying().(*types.Basic); ok && t.t != types.Type(b) {
			return b.Name() + "(" + expr + ")"
		}
		return expr
	case t.k == kBytes:
		return "encBytes(" + expr + ")"
	case t.k == kError:
		return "encErr(" + expr + ")"
	case t.k == kHandle:
		return "henc(" + expr + ")"
	case t.k == kValue && !t.ptr:
		return t.val.enc + "(" + expr + ")"
	}
	name := g.helper("enc:"+t.key, "enc", func(name string) string {
		T := g.ts(t.t)
		var b strings.Builder
		fmt.Fprintf(&b, "func %s(v %s) any {\n", name, T)
		switch {
		case t.ptr:
			inner := *t
			inner.ptr, inner.t = false, t.t.(*types.Pointer).Elem()
			inner.key = types.TypeString(inner.t, nil)
			fmt.Fprintf(&b, "\tif v == nil {\n\t\treturn nil\n\t}\n\treturn %s\n}\n", g.enc(&inner, "*v"))
		case t.k == kDTO:
			b.WriteString("\treturn map[string]any{\n")
			for _, f := range t.fields {
				if f.skipped == "" {
					fmt.Fprintf(&b, "\t\t%q: %s,\n", f.name, g.enc(f.t, "v."+f.name))
				}
			}
			b.WriteString("\t}\n}\n")
		case t.k == kSnap:
			b.WriteString("\tif v == nil {\n\t\treturn nil\n\t}\n\tm := map[string]any{}\n")
			for _, gt := range t.gets {
				if gt.hasErr {
					fmt.Fprintf(&b, "\tif x, err := v.%s(); err == nil {\n\t\tm[%q] = %s\n\t}\n", gt.name, gt.name, g.enc(gt.t, "x"))
				} else {
					fmt.Fprintf(&b, "\tm[%q] = %s\n", gt.name, g.enc(gt.t, "v."+gt.name+"()"))
				}
			}
			b.WriteString("\treturn m\n}\n")
		case t.k == kSlice:
			fmt.Fprintf(&b, "\tout := make([]any, len(v))\n\tfor i, e := range v {\n\t\tout[i] = %s\n\t}\n\treturn out\n}\n", g.enc(t.elem, "e"))
		case t.k == kMap:
			fmt.Fprintf(&b, "\tout := make(map[string]any, len(v))\n\tfor k, e := range v {\n\t\tout[k] = %s\n\t}\n\treturn out\n}\n", g.enc(t.elem, "e"))
		default:
			panic("gen: sem codificador para " + t.key)
		}
		return b.String()
	})
	return name + "(" + expr + ")"
}
