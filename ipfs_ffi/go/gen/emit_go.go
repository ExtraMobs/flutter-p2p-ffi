func cat(t *tinfo) string {
	switch t.k {
	case kHandle:
		return "handle"
	case kBytes:
		return "bytes"
	case kValue:
		return "value"
	}
	b := t.t.Underlying().(*types.Basic)
	switch {
	case b.Info()&types.IsBoolean != 0:
		return "bool"
	case b.Info()&types.IsInteger != 0:
		return "int"
	case b.Info()&types.IsFloat != 0:
		return "double"
	}
	return "string"
}
