package main

import (
	"fmt"
	"go/types"
	"sort"
	"strings"
)

// pkgName: qualifies a type by the package short name (mfs.File).
func pkgName(p *types.Package) string { return p.Name() }

// emitAPI: the Go → Dart checklist per package, with omissions and reasons.
func emitAPI(m *model, fns []*fn) []byte {
	byPkg := map[string][]*fn{}
	for _, f := range fns {
		byPkg[f.pkg.Path()] = append(byPkg[f.pkg.Path()], f)
	}
	var b strings.Builder
	b.WriteString("# p2p_ffi API\n\nGenerated by `go run ./gen` (in `go/`) from `go/gen/roots.txt`; do not edit.\n")
	b.WriteString("Each line is an exposed Go symbol and where it is in Dart.\n")
	for _, pkg := range sortedKeys(byPkg) {
		fmt.Fprintf(&b, "\n## `%s` → `package:p2p_ffi/%s`\n\n| Go | Dart | Mode |\n|---|---|---|\n", pkg, dartPath(pkg))
		var omitted []string
		for _, f := range byPkg[pkg] {
			if f.why != "" {
				omitted = append(omitted, fmt.Sprintf("- `%s`: %s", goDoc(f.obj), f.why))
				continue
			}
			dart := memberName(f.obj.Name())
			switch {
			case f.setter:
				dart = className(f.recv) + "." + dart + " ="
			case f.recv != nil:
				dart = className(f.recv) + "." + dart
			case isFactory(f):
				dart = "factory " + className(f.results[0])
			}
			mode := "sync"
			switch {
			case isConstObj(f.obj):
				mode = "const"
			case f.cast != nil:
				mode = "cast"
			case f.field:
				mode = "field"
			case f.stream != nil:
				mode = "Stream"
			case f.async:
				mode = "Future"
			}
			doc := goDoc(f.obj)
			switch {
			case f.cast != nil:
				doc = types.TypeString(f.recv.t, pkgName) + " → x.(" + types.TypeString(f.cast.t, pkgName) + ")"
			case f.field:
				doc = "(" + types.TypeString(f.recv.t, pkgName) + ")." + f.obj.Name() + " " + types.TypeString(f.obj.Type(), pkgName)
			}
			fmt.Fprintf(&b, "| `%s` | `%s` | %s |\n", doc, dart, mode)
		}
		if len(omitted) > 0 {
			b.WriteString("\nOmitted:\n\n" + strings.Join(omitted, "\n") + "\n")
		}
	}

	var fields, opts []string
	for _, key := range sortedKeys(m.types) {
		t := m.types[key]
		if t.ptr {
			continue
		}
		for _, f := range t.fields {
			if t.k == kDTO && f.skipped != "" {
				fields = append(fields, fmt.Sprintf("- `%s.%s`: %s", key, f.name, f.skipped))
			}
		}
		if t.k == kOpts {
			for _, c := range t.ctors {
				if ok, why := okOptCtor(c); !ok {
					opts = append(opts, fmt.Sprintf("- `%s.%s` (%s): %s", t.named.Obj().Pkg().Name(), strings.Join(c.path, "."), t.named.Obj().Name(), why))
				}
			}
		}
	}
	sort.Strings(opts)
	if len(fields) > 0 {
		b.WriteString("\n## Struct fields that do not cross the bridge\n\n" + strings.Join(fields, "\n") + "\n")
	}
	if len(opts) > 0 {
		b.WriteString("\n## Omitted option constructors\n\n" + strings.Join(opts, "\n") + "\n")
	}
	b.WriteString("\n## Adaptations (generator rules and hand-written code)\n\n")
	for _, a := range adaptations {
		b.WriteString("- " + a + "\n")
	}
	return []byte(b.String())
}

